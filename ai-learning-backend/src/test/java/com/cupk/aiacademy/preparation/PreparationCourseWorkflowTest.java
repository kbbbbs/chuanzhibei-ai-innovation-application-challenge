package com.cupk.aiacademy.preparation;

import com.cupk.aiacademy.common.BusinessException;
import com.cupk.aiacademy.mapper.ChapterMapper;
import com.cupk.aiacademy.mapper.LessonMapper;
import com.cupk.aiacademy.pojo.Chapter;
import com.cupk.aiacademy.pojo.Lesson;
import com.cupk.aiacademy.rag.CourseKnowledgeService;
import com.cupk.aiacademy.rag.NativeRagService;
import com.cupk.aiacademy.service.CourseImportService;
import com.cupk.aiacademy.service.PermissionService;
import com.cupk.aiacademy.service.QuestionService;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.util.List;
import java.util.Map;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

class PreparationCourseWorkflowTest {
    private final PreparationService preparations = mock(PreparationService.class);
    private final ChapterMapper chapters = mock(ChapterMapper.class);
    private final LessonMapper lessons = mock(LessonMapper.class);
    private final CourseKnowledgeService knowledge = mock(CourseKnowledgeService.class);
    private JdbcTemplate jdbc;
    private PreparationCourseWorkflow workflow;

    @BeforeEach void setup() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource("jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1;DATABASE_TO_LOWER=TRUE", "sa", ""));
        jdbc.execute("CREATE TABLE t_course(id INT PRIMARY KEY,title VARCHAR,description VARCHAR,status INT)");
        jdbc.execute("CREATE TABLE t_chapter(id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,course_id INT,title VARCHAR,description VARCHAR,sort_order INT,status INT)");
        jdbc.execute("CREATE TABLE t_lesson(id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,chapter_id INT,title VARCHAR,content VARCHAR,resource_type VARCHAR,resource_url VARCHAR,video_url VARCHAR,video_resource_id BIGINT,duration INT,sort_order INT,status INT,updated_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE t_question(id BIGINT PRIMARY KEY,course_id INT,title VARCHAR,options VARCHAR,answer VARCHAR,analysis VARCHAR,status INT)");
        jdbc.execute("CREATE TABLE t_ai_preparation(id BIGINT PRIMARY KEY,project_status VARCHAR,current_stage VARCHAR,published_course_id INT,updated_at TIMESTAMP)");
        jdbc.update("INSERT INTO t_course VALUES(42,'算法','说明',1)");
        jdbc.update("INSERT INTO t_chapter VALUES(10,42,'原章','',1,1)");
        jdbc.update("INSERT INTO t_lesson(id,chapter_id,title,content,resource_type,video_url,video_resource_id,sort_order,status) VALUES(20,10,'原课时','教师原文','video','/video.mp4',88,1,1)");
        jdbc.update("INSERT INTO t_ai_preparation VALUES(1,'DRAFT','READY_TO_PUBLISH',NULL,CURRENT_TIMESTAMP)");
        var draft = new PreparationModels.View();
        draft.setId(1L); draft.setTeacherId(7); draft.setProjectStatus("DRAFT");
        var config = new PreparationModels.Config(); config.setTargetCourseId(42); config.setIncludeQuestions(false); draft.setConfig(config);
        var outline = new PreparationModels.Outline();
        var chapter = new PreparationModels.ChapterDraft(); chapter.setChapterKey("chapter-1"); chapter.setTitle("生成章");
        var lesson = new PreparationModels.LessonDraft(); lesson.setLessonKey("lesson-1"); lesson.setTitle("新课时"); lesson.setContentMd("# 生成内容");
        chapter.setLessons(List.of(lesson)); outline.setChapters(List.of(chapter)); draft.setOutline(outline); draft.setLessons(List.of(lesson));
        when(preparations.get(1L)).thenReturn(draft);
        when(chapters.insert(any(Chapter.class))).thenAnswer(call -> {
            Chapter value = call.getArgument(0); value.setId(11);
            jdbc.update("INSERT INTO t_chapter VALUES(11,?,?,?,?,?)", value.getCourseId(), value.getTitle(), value.getDescription(), value.getSortOrder(), value.getStatus()); return 1;
        });
        when(lessons.insert(any(Lesson.class))).thenAnswer(call -> {
            Lesson value = call.getArgument(0); value.setId(21);
            jdbc.update("INSERT INTO t_lesson(id,chapter_id,title,content,status) VALUES(21,?,?,?,?)", value.getChapterId(), value.getTitle(), value.getContent(), value.getStatus()); return 1;
        });
        when(lessons.selectById(20)).thenAnswer(call -> {
            Lesson value = new Lesson(); value.setId(20); value.setTitle("原课时"); value.setContent("教师原文"); return value;
        });
        when(lessons.updateById(any(Lesson.class))).thenAnswer(call -> {
            Lesson value = call.getArgument(0); return jdbc.update("UPDATE t_lesson SET title=?,content=? WHERE id=?", value.getTitle(), value.getContent(), value.getId());
        });
        workflow = new PreparationCourseWorkflow(preparations, knowledge, mock(PermissionService.class), chapters, lessons,
                mock(QuestionService.class), jdbc, new ObjectMapper().findAndRegisterModules(), mock(NativeRagService.class), mock(CourseImportService.class));
        workflow.initialize();
    }

    @Test void replacingPreservesLessonIdentityVideoAndPublishedStateAndCanBeRolledBack() {
        String version = String.valueOf(workflow.preview(1L).get("courseVersion"));
        var request = new PreparationCourseWorkflow.ApplyRequest(version, List.of(new PreparationCourseWorkflow.Replacement("lesson-1", 20)));
        var result = workflow.apply(1L, request);
        assertEquals(1, result.get("lessonsReplaced"));
        assertEquals("# 生成内容", jdbc.queryForObject("SELECT content FROM t_lesson WHERE id=20", String.class));
        assertEquals(88L, jdbc.queryForObject("SELECT video_resource_id FROM t_lesson WHERE id=20", Long.class));
        assertEquals(1, jdbc.queryForObject("SELECT status FROM t_course WHERE id=42", Integer.class));
        assertEquals(result.get("courseId"), workflow.apply(1L, request).get("courseId"));
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM course_preparation_application", Integer.class));
        workflow.rollback(1L);
        assertEquals("教师原文", jdbc.queryForObject("SELECT content FROM t_lesson WHERE id=20", String.class));
        assertEquals(true, workflow.rollback(1L).get("rolledBack"));
    }

    @Test void changedCourseRequiresNewPreviewAndDoesNotWriteAnything() {
        String version = String.valueOf(workflow.preview(1L).get("courseVersion"));
        jdbc.update("UPDATE t_lesson SET content='另一位教师新修改' WHERE id=20");
        assertThrows(BusinessException.class, () -> workflow.apply(1L, new PreparationCourseWorkflow.ApplyRequest(version, List.of())));
        verify(chapters, never()).insert(any(Chapter.class));
    }

    @Test void defaultApplicationAppendsAndRollbackArchivesNewIds() {
        String version = String.valueOf(workflow.preview(1L).get("courseVersion"));
        var result = workflow.apply(1L, new PreparationCourseWorkflow.ApplyRequest(version, List.of()));
        assertEquals(1, result.get("chaptersCreated")); assertEquals(1, result.get("lessonsCreated"));
        workflow.rollback(1L);
        assertEquals(0, jdbc.queryForObject("SELECT status FROM t_lesson WHERE id=21", Integer.class));
        assertEquals("教师原文", jdbc.queryForObject("SELECT content FROM t_lesson WHERE id=20", String.class));
    }

    @Test void sameTargetCannotBeReplacedTwice() {
        String version = String.valueOf(workflow.preview(1L).get("courseVersion"));
        var mapping = new PreparationCourseWorkflow.Replacement("lesson-1", 20);
        assertThrows(BusinessException.class, () -> workflow.apply(1L, new PreparationCourseWorkflow.ApplyRequest(version, List.of(mapping, mapping))));
    }
}
