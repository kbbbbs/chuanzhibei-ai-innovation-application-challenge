CREATE TABLE IF NOT EXISTS native_graph_definition (
 id VARCHAR(36) PRIMARY KEY, course_id INTEGER NOT NULL, chapter_id INTEGER NOT NULL,
 owner_id INTEGER NOT NULL, title VARCHAR(200) NOT NULL, document_id VARCHAR(36) NOT NULL,
 document_version INTEGER NOT NULL, parse_revision INTEGER NOT NULL, index_version VARCHAR(36) NOT NULL,
 page_start INTEGER NOT NULL, page_end INTEGER NOT NULL, revision INTEGER NOT NULL DEFAULT 1,
 published_version INTEGER, state VARCHAR(32) NOT NULL DEFAULT 'REVIEW_REQUIRED',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS native_graph_version (
 graph_id VARCHAR(36) NOT NULL, version INTEGER NOT NULL, snapshot_json LONGTEXT NOT NULL,
 created_by INTEGER NOT NULL, reviewed_by INTEGER, reviewed_at TIMESTAMP,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(graph_id,version)
);
CREATE TABLE IF NOT EXISTS native_graph_job (
 id VARCHAR(36) PRIMARY KEY, graph_id VARCHAR(36) NOT NULL, version INTEGER NOT NULL,
 actor_id INTEGER NOT NULL, actor_role VARCHAR(20) NOT NULL, status VARCHAR(32) NOT NULL DEFAULT 'QUEUED',
 attempts INTEGER NOT NULL DEFAULT 0, lease_until TIMESTAMP, lease_token VARCHAR(36), error_message VARCHAR(300),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT native_graph_job_version UNIQUE(graph_id,version)
);
CREATE TABLE IF NOT EXISTS native_graph_review (
 id VARCHAR(36) PRIMARY KEY, graph_id VARCHAR(36) NOT NULL, version INTEGER NOT NULL,
 actor_id INTEGER NOT NULL, action VARCHAR(32) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE native_graph_job ADD COLUMN lease_token VARCHAR(36);
CREATE TABLE IF NOT EXISTS native_graph_extraction (
 id VARCHAR(36) PRIMARY KEY, graph_id VARCHAR(36) NOT NULL, input_revision INTEGER NOT NULL,
 output_revision INTEGER, actor_id INTEGER NOT NULL, model_name VARCHAR(200) NOT NULL,
 prompt_version VARCHAR(50) NOT NULL, source_fingerprint VARCHAR(64) NOT NULL,
 status VARCHAR(32) NOT NULL, error_message VARCHAR(300),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
