from copy import deepcopy
from pathlib import Path
from zipfile import ZipFile
import hashlib
import sys

from docx import Document
from docx.text.paragraph import Paragraph


def find_paragraph(document, exact_text):
    for paragraph in document.paragraphs:
        if paragraph.text.strip() == exact_text:
            return paragraph
    raise ValueError(f"Paragraph not found: {exact_text}")


def set_text_keep_format(paragraph, text):
    if paragraph.runs:
        paragraph.runs[0].text = text
        for run in paragraph.runs[1:]:
            run.text = ""
    else:
        paragraph.add_run(text)


def clone_paragraph_after(paragraph, text):
    element = deepcopy(paragraph._p)
    new_paragraph = Paragraph(element, paragraph._parent)
    set_text_keep_format(new_paragraph, text)
    paragraph._p.addnext(element)
    return new_paragraph


def media_hashes(path):
    with ZipFile(path) as archive:
        return {
            name: hashlib.sha256(archive.read(name)).hexdigest()
            for name in archive.namelist()
            if name.startswith("word/media/")
        }


